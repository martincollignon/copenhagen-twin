#!/usr/bin/env python3
"""QA of the converted LoD2 roofs -> data/lod2/report.md.

Coverage (count and footprint area), roofer ridge / eave / ground vs the DSM-derived values in cph-geodata.json, edge
matching, shell closure (an edge-manifold check on the roofer solid, since val3dity is not installed), the acquisition-date
gate, and the list of skipped / failed buildings.

    uv run --project tools/lod2 python tools/lod2/qa.py
"""
from __future__ import annotations

import collections
import json
import statistics as st
import sys
from pathlib import Path

import numpy as np

import common
import convert


def poly_area(ring: list[float]) -> float:
    a = 0.0
    n = len(ring) // 2
    for i in range(n):
        j = (i + 1) % n
        a += ring[2 * i] * ring[2 * j + 1] - ring[2 * j] * ring[2 * i + 1]
    return abs(a) / 2


def stats(x: list[float]) -> str:
    if not x:
        return "n=0"
    ax = sorted(abs(v) for v in x)
    return f"n={len(x)} median={st.median(x):+.2f} MAE={st.mean(ax):.2f} p90|e|={ax[int(.9 * (len(ax) - 1))]:.2f} m"


def main() -> int:
    out_dir = common.OUT_DIR
    index = json.loads((out_dir / "index.json").read_text())
    geo = common.load_geodata()
    by = {b["id"]: b for b in geo["buildings"]}
    heroes = {h["building_id"] for h in geo.get("heroes", [])}
    entries = index["buildings"]
    blobs = {t: (out_dir / v["file"]).read_bytes() for t, v in index["tiles"].items()}

    measured = {k: v for k, v in entries.items() if "offset" in v}
    skipped = {k: v for k, v in entries.items() if "offset" not in v}
    all_ids = [b["id"] for b in geo["buildings"] if b["id"] not in heroes]
    missing = [i for i in all_ids if i not in entries]  # never came back from roofer (outside every prepared tile)
    area = {i: poly_area(by[i]["ring"]) for i in all_ids}
    tot_area = sum(area.values())

    d_ridge, d_eave, d_ground, d_zmax = [], [], [], []
    types, planes, rmse, dens, edge_frac, closed = collections.Counter(), [], [], [], [], 0
    horiz_pitched = 0
    for gid, e in measured.items():
        b = by[gid]
        r = convert.unpack_record(blobs[e["tile"]][e["offset"]:e["offset"] + e["length"]])
        zmax = float(r["pos"][:, 1].max())
        d_zmax.append(zmax - b["ridge"])
        if e.get("roofer_ridge") is not None:
            d_ridge.append(e["roofer_ridge"] - common.ORIGIN[2] - b["ridge"])
        roof = r["pos"][r["tri"][r["kind"] == convert.ROOF]]
        if len(roof):
            d_eave.append(float(np.median(roof[:, :, 1])) - b["eave"])
        if e.get("roofer_ground") is not None:
            d_ground.append(e["roofer_ground"] - common.ORIGIN[2] - b["ground"])
        types[e["roof_type"]] += 1
        if e["planes"] is not None:
            planes.append(e["planes"])
        if e["rmse"] is not None:
            rmse.append(e["rmse"])
        if e["density"] is not None:
            dens.append(e["density"])
        closed += bool(e["closed"])
        # share of footprint edge length that has a roofer outer wall
        edges = convert.footprint_edges(b)
        ln = sum(x[6] for x in edges) or 1
        edge_frac.append(sum(x[6] for x, t in zip(edges, r["top"]) if t is not None) / ln)
        if b["ridge"] - b["eave"] > 1.5 and e["roof_type"] == "horizontal":
            horiz_pitched += 1

    reasons = collections.Counter(v["reason"].split(" (")[0] if v.get("reason") else "?" for v in skipped.values())
    # reasons embed numbers (densities, percentages): bucket by their leading words
    bucket = collections.Counter()
    for v in skipped.values():
        r = v.get("reason", "?")
        bucket["a point-cloud nodata share above %.0f%%" % (convert.MAX_NODATA * 100) if "has no points" in r else
               "point density below %.0f/m2" % convert.MIN_DENSITY if r.startswith("point density") else r] += 1
    meas_area = sum(area[i] for i in measured)
    small = [i for i in skipped if area[i] < 25]
    small_area = sum(area[i] for i in small)

    L = []
    w = L.append
    w("# LoD2 roofs: QA report\n")
    w(f"Generated by `tools/lod2/qa.py`. Roofer `{common.ROOFER_IMAGE}`, DHM Punktsky scanned "
      f"{', '.join(sorted({t['scan_date'] for t in index['tiles'].values()}))}. Frame and units as in `docs/cph-geodata-schema.md`.\n")
    w("## Coverage\n")
    w(f"- Geodata buildings (excluding {len(heroes)} hero): **{len(all_ids)}**; tiles: {', '.join(sorted(index['tiles']))}.")
    w(f"- Roofer returned a record for {len(entries)}; **{len(measured)} ({len(measured) / len(all_ids):.1%}) have a LoD2.2 roof mesh** (`conf: measured`), "
      f"covering {meas_area / tot_area:.1%} of the footprint area. {len(missing)} buildings never reached a prepared tile.")
    w(f"- **{len(skipped)} keep the flat extrusion** (`conf: inferred`), of which {len(small)} are under 25 m2 footprint (sheds, median "
      f"{st.median([area[i] for i in small]) if small else 0:.0f} m2; {small_area / tot_area:.1%} of the area).\n")
    w("| why a building has no LoD2 roof | buildings |\n|---|---|")
    for r, c in bucket.most_common():
        w(f"| {r} | {c} |")
    w("")
    w("Roof type of the meshed buildings: " + ", ".join(f"{k}: {v}" for k, v in types.most_common()) + ".\n")
    w("## Heights against the DSM-derived values\n")
    w("Roofer values are absolute DVR90 minus 6.84 (local y); the DSM values are `ridge` / `eave` / `ground` in `cph-geodata.json` "
      "(DSM percentiles, so `eave` is a definition gap rather than an error).\n")
    w(f"- roofer ridge (`rf_h_roof_max`) minus DSM ridge: {stats(d_ridge)}")
    w(f"- LoD2.2 mesh max y minus DSM ridge: {stats(d_zmax)}")
    w(f"- median roof-triangle height minus DSM eave: {stats(d_eave)}")
    w(f"- roofer ground minus DTM ground: {stats(d_ground)}")
    w(f"- buildings whose DSM ridge is more than 1.5 m above the eave yet came out `horizontal`: {horiz_pitched}\n")
    w("## Geometry quality\n")
    w(f"- roofer `rmse_lod22`: median {st.median(rmse):.2f} m, p90 {sorted(rmse)[int(.9 * (len(rmse) - 1))]:.2f} m (roofer's own fit measure; not independent).")
    w(f"- roof planes: median {st.median(planes):.0f}, p90 {sorted(planes)[int(.9 * (len(planes) - 1))]}, max {max(planes)}; point density median {st.median(dens):.1f}/m2.")
    w(f"- footprint edge length with a matched roofer outer wall (<= {convert.MATCH_DIST} m, same side): median {st.median(edge_frac):.0%}, "
      f"{sum(f > 0.99 for f in edge_frac)} buildings fully matched. Unmatched edges keep the DSM eave.")
    w(f"- roofer solids that are closed 2-manifold shells: {closed}/{len(measured)} ({closed / max(len(measured), 1):.1%}). "
      "**val3dity is not installed here and this roofer build does not emit `val3dity_lod22`**, so this edge-manifold check is the only "
      "validity test; run `val3dity` on the CityJSONSeq in `data/raw/lod2/work/<tile>/out` for the formal ISO 19107 verdict.")
    w(f"- binary size: {sum(len(b) for b in blobs.values()) / 1e6:.2f} MB for {len(measured)} meshes; index.json {Path(out_dir / 'index.json').stat().st_size / 1e6:.2f} MB.\n")
    w("## Acquisition-date gate\n")
    post = [k for k, v in skipped.items() if "after the point cloud" in v.get("reason", "")]
    w(f"- Every tile was scanned in {', '.join(sorted({t['scan_date'] for t in index['tiles'].values()}))}. {len(post)} buildings have a BBR "
      f"`year` later than the scan year: they are `inferred`, get no mesh, and the engine keeps the flat extrusion.")
    if post:
        w("  " + ", ".join(f"{p} ({by[p].get('year')})" for p in sorted(post, key=lambda p: -(by[p].get('year') or 0))[:20]) + (" ..." if len(post) > 20 else ""))
    w("- Buildings whose BBR year equals the scan year are kept (the roof may have been unfinished): "
      f"{sum(1 for k in measured if by[k].get('year') == int(index['tiles'][measured[k]['tile']]['scan_date'][:4]))}.\n")
    w("## Skipped or failed buildings\n")
    byreason = collections.defaultdict(list)
    for k, v in skipped.items():
        byreason[v.get("reason", "?")].append(k)
    w("Footprint area in m2 in brackets. Full machine-readable list: `index.json` entries without `offset`.\n")
    for reason, ids in sorted(byreason.items(), key=lambda kv: -len(kv[1])):
        w(f"- **{reason}** ({len(ids)}): " + ", ".join(f"{i.split(':')[1]} ({area[i]:.0f})" for i in sorted(ids, key=lambda i: -area[i])[:25]) + (" ..." if len(ids) > 25 else ""))
    big = sorted((i for i in skipped if area[i] >= 25), key=lambda i: -area[i])[:15]
    w("\nLargest buildings without a LoD2 roof: " + ", ".join(f"{i.split(':')[1]} ({area[i]:.0f} m2, {skipped[i].get('reason')})" for i in big) + ".")
    if missing:
        w(f"\nNot reached by any tile: {len(missing)} (outside the prepared tiles).")
    (out_dir / "report.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:30]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
