#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["pyproj"]
# ///
"""Citywide teleport presets (milestone C5): positions on the citywide road graph.

Each place is a WGS84 spot plus the street names that belong to it; the tool finds the vehicular link of the graph (primary, secondary,
residential) that carries one of those names nearest to the spot (else the nearest vehicular link within --reach), puts the preset at a
point along it and heads along the link, in the local frame of the twin (NS37 origin, x east, z south, heading h: forward is
(sin h, cos h)). Writes js/city-teleports.js (committed: the presets must not depend on data that is gitignored).

    uv run tools/cph-geodata/city_teleports.py [--roadgraph data/city/roadgraph.json] [--out js/city-teleports.js]
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from frame import ORIGIN  # noqa: E402

VEHICULAR = {"primary", "secondary", "residential"}

#           key               name                       sub                              lat      lon      street names of the place
PLACES = [
    ("rhus", "Rådhuspladsen", "Indre By · town hall square", 55.6761, 12.5683, ["Vester Voldgade", "H.C. Andersens Boulevard", "Vesterbrogade"]),
    ("nyhavn", "Nyhavn", "Indre By · the canal", 55.6798, 12.5911, ["Nyhavn", "Nyhavnsbroen", "Kongens Nytorv", "Sankt Annæ Plads"]),
    ("slot", "Christiansborg", "Slotsholmen", 55.6761, 12.5800, ["Christiansborg Slotsplads", "Frederiksholms Kanal", "Børsgade", "Slotsholmsgade"]),
    ("brygge", "Islands Brygge", "Amager · the harbour front", 55.6640, 12.5750, ["Islands Brygge"]),
    ("vesterbro", "Istedgade", "Vesterbro", 55.6706, 12.5555, ["Istedgade", "Vesterbro Torv", "Vesterbrogade"]),
    ("frbrhus", "Frederiksberg Rådhus", "Frederiksberg · Smallegade", 55.6786, 12.5320, ["Smallegade", "Frederiksberg Allé"]),
    ("frballe", "Frederiksberg Allé", "Frederiksberg · the avenue", 55.6735, 12.5400, ["Frederiksberg Allé"]),
    ("trianglen", "Trianglen", "Østerbro", 55.7013, 12.5755, ["Østerbrogade", "Øster Allé", "Trianglen"]),
]


def main() -> int:
    from pyproj import Transformer

    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--roadgraph", default="data/city/roadgraph.json")
    ap.add_argument("--out", default="js/city-teleports.js")
    ap.add_argument("--reach", type=float, default=160.0, help="metres from the spot to the street when no name matches")
    ap.add_argument("--name-reach", type=float, default=300.0)
    args = ap.parse_args()
    g = json.loads(Path(args.roadgraph).read_text())
    nodes, names, classes = g["nodes"], g["names"], g["classes"]
    t = Transformer.from_crs("EPSG:4326", "EPSG:25832", always_xy=True)
    rows = []
    for key, name, sub, lat, lon, hints in PLACES:
        e, n = t.transform(lon, lat)
        x, z = e - ORIGIN[0], -(n - ORIGIN[1])
        best = None
        for l in g["links"]:
            if classes[l[7]] not in VEHICULAR or l[0] == l[1] or l[2] + l[3] == 0:
                continue
            ax, az, bx, bz = nodes[2 * l[0]], nodes[2 * l[0] + 1], nodes[2 * l[1]], nodes[2 * l[1] + 1]
            ln = math.hypot(bx - ax, bz - az)
            if ln < 8:  # a long enough run to stand on
                continue
            dx, dz = bx - ax, bz - az
            tt = max(0.0, min(1.0, ((x - ax) * dx + (z - az) * dz) / (dx * dx + dz * dz)))
            px, pz = ax + dx * tt, az + dz * tt
            d = math.hypot(px - x, pz - z)
            nm = names[l[6]] if l[6] is not None and l[6] < len(names) else ""
            named = any(h.lower() in (nm or "").lower() for h in hints)
            score = d - (200 if named else 0)  # a named street within reach beats a nearer unnamed one
            if d > (args.name_reach if named else args.reach):
                continue
            if best is None or score < best[0]:
                # travel the way the lanes allow (a one-way link: along it); else along a -> b
                fwd = l[2] > 0 or l[3] == 0
                ux, uz = (dx, dz) if fwd else (-dx, -dz)
                best = (score, d, nm, (ax + bx) / 2 if tt in (0.0, 1.0) else px, (az + bz) / 2 if tt in (0.0, 1.0) else pz, math.atan2(ux, uz), classes[l[7]])
        if best is None:
            print(f"{key}: no street near", file=sys.stderr)
            continue
        _, d, nm, px, pz, h, cls = best
        rows.append((key, name, sub, round(px, 1), round(pz, 1), round(h, 2)))
        print(f"{key:10s} {name:22s} on {nm or '(unnamed)'} ({cls}), {d:.0f} m from the spot -> x {px:.1f}, z {pz:.1f}, heading {h:.2f}")
    lines = [
        "// js/city-teleports.js",
        "// GENERATED by tools/cph-geodata/city_teleports.py from data/city/roadgraph.json: do not edit by hand.",
        "// Citywide teleport presets (local frame, NS37 origin; heading h: forward is (sin h, cos h)), each on a vehicular link of the",
        "// citywide road graph, heading along it. They only mean something once the tile index covers them (js/main.js hides the others).",
        "",
        "export const CITY_TELEPORT_LOCATIONS = {",
    ]
    for key, name, sub, x, z, h in rows:
        lines.append(f"  {key}: {{ name: {json.dumps(name, ensure_ascii=False)}, sub: {json.dumps(sub, ensure_ascii=False)}, x: {x}, z: {z}, heading: {h} }},")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("};")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
